#!/usr/bin/env node
// Reads the master VO timing.json and emits a JS module with per-scene offsets
// and a word -> { start, end } map per scene. Scenes import this to sync
// animations to exact VO word timings (same discipline as the Remotion pipeline).

import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");

const master = JSON.parse(
  readFileSync(join(root, "assets/voiceover/master-timing.json"), "utf8"),
);

let offset = 0;
const scenes = master.map((scene) => {
  const start = offset;
  const duration = scene.durationSeconds;
  offset += duration;
  const words = {};
  for (const w of scene.words) {
    const key = w.word.toLowerCase().replace(/[^a-z0-9]/g, "");
    if (!words[key]) {
      words[key] = { start: w.start, end: w.end, absStart: start + w.start };
    }
  }
  return {
    id: scene.sceneId,
    start,
    duration,
    end: offset,
    text: scene.text,
    words,
    rawWords: scene.words.map((w) => ({ ...w, abs: start + w.start })),
  };
});

const out = {
  totalDuration: offset,
  scenes,
};

writeFileSync(join(root, "timeline-offsets.json"), JSON.stringify(out, null, 2));

// Also emit a browser-friendly JS module for <script type="module"> imports
const js = `// Auto-generated by scripts/build-timeline.mjs — do not edit by hand.
export const TIMELINE = ${JSON.stringify(out, null, 2)};
export const SCENES = TIMELINE.scenes;
export const getScene = (id) => SCENES.find((s) => s.id === id);
export const wordTime = (sceneId, word) => {
  const s = getScene(sceneId);
  if (!s) return 0;
  const key = word.toLowerCase().replace(/[^a-z0-9]/g, "");
  return s.words[key]?.start ?? 0;
};
`;
writeFileSync(join(root, "assets/timeline.js"), js);

console.log(`Wrote timeline-offsets.json and assets/timeline.js`);
console.log(`Total duration: ${offset.toFixed(3)}s across ${scenes.length} scenes`);
for (const s of scenes) {
  console.log(
    `  ${s.id.padEnd(28)} start=${s.start.toFixed(2).padStart(6)}s  dur=${s.duration.toFixed(2)}s`,
  );
}
